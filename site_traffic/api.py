"""
HTTP entry point (thin): all logic lives in site_traffic.service.run_site.

    uvicorn site_traffic.api:app --port 8000

    POST|GET /api/test/traffic-data/            (also /test/traffic-data/)
    GET      /api/test/traffic-report/{site_key}  PDF written by a snapshot=true request
"""
from __future__ import annotations

import os
import re

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import FileResponse
from starlette.concurrency import run_in_threadpool

from .service import REPORT_NAME, ServiceError, output_root, run_site

app = FastAPI(title="Site Traffic Analysis API", version="0.2.0")


def _run(params: dict) -> dict:
    try:
        return run_site(params)
    except ServiceError as e:
        raise HTTPException(e.status, e.message)


@app.get("/health")
def health():
    return {"status": "ok"}


@app.get("/api/test/traffic-data/")
@app.get("/test/traffic-data/")
def traffic_data_get(request: Request):
    return _run(dict(request.query_params))


@app.post("/api/test/traffic-data/")
@app.post("/test/traffic-data/")
async def traffic_data_post(request: Request):
    try:
        body = await request.json()
    except Exception:
        body = {}
    if not isinstance(body, dict):
        raise HTTPException(422, "JSON object body expected")
    return await run_in_threadpool(_run, {**request.query_params, **body})      # body wins over query string


@app.get("/api/test/traffic-report/{site_key}")
@app.get("/test/traffic-report/{site_key}")
def traffic_report(site_key: str):
    """Download the PDF generated by a snapshot request for that site."""
    if not re.fullmatch(r"site_-?\d+(\.\d+)?_-?\d+(\.\d+)?", site_key):
        raise HTTPException(404, "Unknown report")
    path = os.path.join(output_root(), site_key, REPORT_NAME)
    if not os.path.isfile(path):
        raise HTTPException(404, "Report not generated yet - call the traffic-data endpoint with snapshot=true")
    return FileResponse(path, media_type="application/pdf", filename=f"{site_key}_{REPORT_NAME}")
